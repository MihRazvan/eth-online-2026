import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {analysisHandler} from './http.mjs';
const configPath=process.env.DATA_CONFIG;
if(!configPath)throw new Error('DATA_CONFIG must point to an existing private analysis configuration file; no fixture fallback');
const config=JSON.parse(readFileSync(configPath));
const server=createServer(analysisHandler({...config,graphApiKey:process.env.GRAPH_API_KEY}));
server.requestTimeout=40000;server.headersTimeout=10000;
server.listen(Number(process.env.DATA_PORT??8787),'127.0.0.1',()=>console.log('usufruct analysis API listening on loopback; credentials remain server-side.'));
for(const signal of ['SIGINT','SIGTERM'])process.once(signal,()=>server.close(()=>process.exit(0)));
